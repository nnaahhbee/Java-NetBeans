  private void addAppointment(Appointment appointment){
   appointments.add(appointment);
  }
  private void removeAppointment(){
    if(!appointments.isEmpty()){
     appointments.remove(0);
    }
  }
  
  private String displayAppointments(){
   StringBuilder result = new StringBuilder();
   result.append("Scheduled Appointments: \n");
   for(Appointment appointment : appointments){
     result.append("Name: ").append(appointment.getName()).append(", Description: ").append(appointment.getDescription())
             .append(", Date: ").append(appointment.getDate()).append(", Time: ").append(appointment.getTime())
             .append(", Waiting Time: ").append(getWaitingTime(appointment)).append(" minutes, Turnaround Time: ")
             .append(getTurnaroundTime(appointment)).append(" minutes\n");
   }
   return result.toString();
  }
  private String viewNextAppointment(){
   if(appointments.isEmpty()){
    return "No appointments scheduled.";
   }else{
    Appointment nextAppointment = appointments.get(0);
    return "Next Appointment:\nName: " + nextAppointment.getName() + " Description: " + nextAppointment.getDescription()
            + ", Date: " + nextAppointment.getDate() + ", Time: " + nextAppointment.getTime() + ", Waiting Time: " + getWaitingTime(nextAppointment)
            + " minutes, Turnaround Time: " + getTurnaroundTime(nextAppointment) + " minutes";
   }
  }
  private long getWaitingTime(Appointment appointment){
    if(appointments.isEmpty() || appointments.get(0) == appointment){
      return 0;
    }
    LocalDateTime previousCreationTime = appointments.get(appointments.indexOf(appointment)-1).getCreationTime();
    long minutes = ChronoUnit.HOURS.between(previousCreationTime, appointment.getCreationTime());
    return minutes;
  }
  private long getTurnaroundTime(Appointment appointment){
    LocalDateTime finishingTime = appointment.getCreationTime().plusHours(Long.parseLong(appointment.getTime()));
    LocalDateTime currentTime = LocalDateTime.now();
    long minutes = ChronoUnit.HOURS.between(currentTime, finishingTime);
    return minutes;
  }
    


