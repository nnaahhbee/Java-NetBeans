class Appointment {
  private String name;  
  private String description;
  private String date;
  private String time;
  private LocalDateTime creationTime;
  
  public Appointment(String name, String description, String date, String time, LocalDateTime creationTime){
     this.name = name;
     this.description = description;
     this.date = date;
     this.time = time;
     this.creationTime = creationTime;
  }
  public String getName(){
   return name;
  }
  public String getDescription(){
   return description;
  }
  public String getDate(){
   return date;
  }
  public String getTime(){
   return time;
  }
  public LocalDateTime getCreationTime(){
   return creationTime;
  }
}
  
 
