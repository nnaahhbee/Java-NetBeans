    private void btnokActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnokActionPerformed
        
        try {
            con.setAutoCommit(false);
            String accno = txtacc.getText();
            String cust_id = labelid.getText();
            String firstname = labelfname.getText();
            String lastname = labellname.getText();
            String date = jLabel9.getText();
            String balance = labelbal.getText();
            String amount = txtamount.getText();
            
            Class.forName("com.mysql.jdbc.Driver");
            con = DriverManager.getConnection("jdbc:mysql://localhost/bank_system","root","");
            
            insert = con.prepareStatement("insert into withdraw(acc_id, cust_id, date, balance, withdraw)value(?,?,?,?,?)");
            insert.setString(1, accno);
            insert.setString(2, cust_id);
            insert.setString(3, date);
            insert.setString(4, balance);
            insert.setString(5, amount);
            
            insert.executeUpdate();
            
            update = con.prepareStatement("update account set balance = balance - ? where acc_id = ?");
            update.setString(1, amount);
            update.setString(2, accno);
            
            update.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Withdraw....");
            con.commit();
            
            
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(Withdraw.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            try {
                con.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(Withdraw.class.getName()).log(Level.SEVERE, null, ex1);
            }
            
            Logger.getLogger(Withdraw.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
        
        
    }//GEN-LAST:event_btnokActionPerformed

