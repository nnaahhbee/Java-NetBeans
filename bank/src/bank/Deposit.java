    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed

        try {
            String accno = txtacc.getText();
            Class.forName("com.mysql.jdbc.Driver");
            con = DriverManager.getConnection("jdbc:mysql://localhost/bank_system","root","");
            
            insert = con.prepareStatement("select c.cust_id, c.firstname, c.lastname, a.balance from customer c, account a where c.cust_id = a.cust_id and a.acc_id = ?");
            insert.setString(1, accno);
            rs = insert.executeQuery();
            
            if(rs.next() == false){
              JOptionPane.showMessageDialog(this, "Account not found");
            }
            else{
              String id = rs.getString(1);
              String firstname = rs.getString(2);
              String lastname = rs.getString(3);
              String balance = rs.getString(4);
            
              labelid.setText(id.trim());
              labelfname.setText(firstname.trim());
              labellname.setText(lastname.trim());
              lblbalance.setText(balance.trim());
              
            
            }
            
            
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(Deposit.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(Deposit.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnfindActionPerformed


