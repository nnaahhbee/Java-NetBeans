class Appointment {
  private String name;
  private String description;
  private String date;
  private String time;
  
  public Appointment(String name, String description, String date, String time){
    this.name = name;
    this.description = description;
    this.date = date;
    this.time = time;
  }
  
  public String getName(){
   return name;
  }
  
  public String getDescription(){
   return description;
  }
  
  public String getDate(){
   return date;
  }
  
  public String getTime(){
   return time;
  }
}

class AppointmentSystem {
 private java.util.Queue<Appointment> appointments;
 
 public AppointmentSystem(){
  appointments = new java.util.LinkedList<>();
 }
 
 public void addAppointment(Appointment appointment){
   appointments.offer(appointment);
 }
 
 public void removeAppoinment(){
   appointments.poll();
 }
 
 public String displayAppointments(){
  StringBuilder result = new StringBuilder();
  result.append("Scheduled Appointments:\n");
  for (Appointment appointment : appointments){
    result.append("Name ").append(appointment.getName()).append(", Description: ").append(appointment.getDescription())
            .append(", Date: ").append(appointment.getDate()).append(", Time: ").append(appointment.getTime());
  }
  return result.toString();
 }
 
 public String viewNextAppointment(){
   if(appointments.isEmpty()){
     return "No appointments scheduled.";
   }else{
     Appointment nextAppointment = appointments.peek();
     return "Next Appointment: \nName: " + nextAppointment.getName() + ", Description: " + nextAppointment.getDescription()
             + ", Date: " + nextAppointment.getDate() + ", Time: " + nextAppointment.getTime();
   }
 }
 
 
 public java.util.Queue<Appointment>getAppointments(){
   return appointments;
 }
 
 private Appointment getLastAppointment(){
   Iterator<Appointment> iterator = appointments.iterator();
   Appointment lastAppointment = null;
   while(iterator.hasNext()){
     lastAppointment = iterator.next();
   }
   return lastAppointment;
 }
}


