    private void add_customerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_add_customerActionPerformed
        // TODO add your handling code here:
        String customerName = JOptionPane.showInputDialog("Enter Customer name:");
        if(customerName != null && !customerName.isEmpty()){
           int numberOfItems = Integer.parseInt(JOptionPane.showInputDialog("Enter number of items purchased:"));
           Customer customer = new Customer(customerName, numberOfItems, currentTime);
           customerQueue.add(customer);
           jTextArea1.append("Customer " + customer.getName() + " added to the queue. \n\n");
        }
    }//GEN-LAST:event_add_customerActionPerformed

    private void next_customerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_next_customerActionPerformed
        // TODO add your handling code here:
        if(!customerQueue.isEmpty()){
          Customer nextCustomer = customerQueue.poll();
          nextCustomer.setWaitingTime(currentTime - nextCustomer.getArrivalTime());
          jTextArea1.append("Processing customer: " + nextCustomer.getName() + "\n");
          jTextArea1.append("Waiting time: " + nextCustomer.getWaitingTime() + " seconds. \n");
          jTextArea1.append("Turnaround time: " + nextCustomer.getTurnaroundTime() + " seconds. \n");
          currentTime += nextCustomer.getProcessingTime();
          jTextArea1.append("Current time: " + currentTime + " seconds. \n\n");
        }else{
          jTextArea1.append("No Customer in the queue.\n\n");
        }
    }//GEN-LAST:event_next_customerActionPerformed

