    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
                String name = nameField.getText();
                LocalDate date = LocalDate.parse(dateField.getText());
                LocalTime time = LocalTime.parse(timeField.getText());
                String description = descriptionField.getText();
                
                if(isAppointmentSlotBooked(date, time)){
                  JOptionPane.showMessageDialog(null, "This appointment slot is already booked!");
                }else{
                appointments.add(new Appointment(name, date, time, description));
                refreshAppointmentArea();
                clearFields();
                JOptionPane.showMessageDialog(null, "Appointment added successfully!");
                }
    }//GEN-LAST:event_addButtonActionPerformed

    private void viewButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewButtonActionPerformed
                    if (appointments.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "No appointments available!");
                } else {
                    Appointment nextAppointment = getNextAvailableAppointment();
                    String message = "Next Available Appointment:\n"
                            + "Name: " + nextAppointment.getName() + "\n"
                            + "Date: " + nextAppointment.getDate() + "\n"
                            + "Time: " + nextAppointment.getTime() + "\n"
                            + "Description: " + nextAppointment.getDescription();
                    JOptionPane.showMessageDialog(null, message);
                }


    }//GEN-LAST:event_viewButtonActionPerformed

    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
       if (appointments.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "No appointments available to remove!");
                } else {
                    appointments.remove(0);
                    refreshAppointmentArea(); 
                    JOptionPane.showMessageDialog(null, "Appointment removed successfully!");
                }
    }//GEN-LAST:event_removeButtonActionPerformed

    
        private Appointment getNextAvailableAppointment() {
        Collections.sort(appointments, Comparator.comparing(Appointment::getDate).thenComparing(Appointment::getTime));
        return appointments.get(0);
    }
        
         private void refreshAppointmentArea() {
        StringBuilder sb = new StringBuilder();
        for (Appointment appointment : appointments) {
            sb.append("Name: ").append(appointment.getName()).append(", Description: ").append(appointment.getDescription())
                    .append(", Date: ").append(appointment.getDate()).append(", Time: ").append(appointment.getTime()).append("\n");
        }
        appointmentArea.setText(sb.toString());
    }
         
        private void clearFields() {
         nameField.setText("");
         dateField.setText("");
         timeField.setText("");
         descriptionField.setText("");
      }


        private boolean isAppointmentSlotBooked(LocalDate date, LocalTime time) {
         for (Appointment appointment : appointments) {
        if (appointment.getDate().equals(date) && appointment.getTime().equals(time)) {
            return true; // Slot is already booked
        }
      }
        return false; // Slot is available
    }
